import api from "../../../../shared/services/api";

const medicineService = {
    /*
    |--------------------------------------------------------------------------
    | LIST
    |--------------------------------------------------------------------------
    */

    getAll(params = {}) {
        return api.get("/master/medicines", {
            params,
        });
    },

    /*
    |--------------------------------------------------------------------------
    | DETAIL
    |--------------------------------------------------------------------------
    */

    getById(id) {
        return api.get(`/master/medicines/${id}`);
    },

    /*
    |--------------------------------------------------------------------------
    | CREATE
    |--------------------------------------------------------------------------
    */

    create(payload) {
        return api.post("/master/medicines", payload);
    },

    /*
    |--------------------------------------------------------------------------
    | UPDATE
    |--------------------------------------------------------------------------
    */

    update(id, payload) {
        return api.put(`/master/medicines/${id}`, payload);
    },

    /*
    |--------------------------------------------------------------------------
    | STATUS
    |--------------------------------------------------------------------------
    */

    toggleStatus(id) {
        return api.patch(`/master/medicines/${id}/status`);
    },

    /*
    |--------------------------------------------------------------------------
    | DELETE
    |--------------------------------------------------------------------------
    */

    remove(id) {
        return api.delete(`/master/medicines/${id}`);
    },
};

export default medicineService;
